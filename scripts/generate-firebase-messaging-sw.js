#!/usr/bin/env node
/**
 * Writes web/firebase-messaging-sw.js from FIREBASE_* env vars.
 * Required for background FCM: initializeApp + onBackgroundMessage + notificationclick.
 *
 * Run from repo root after sourcing .env (see run_production.sh / build_*.sh).
 */
const fs = require("fs");
const path = require("path");

const required = [
  "FIREBASE_API_KEY",
  "FIREBASE_APP_ID_WEB",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_STORAGE_BUCKET",
];

for (const k of required) {
  if (!process.env[k] || String(process.env[k]).trim() === "") {
    console.error(`generate-firebase-messaging-sw.js: missing env ${k}`);
    process.exit(1);
  }
}

const firebaseConfig = {
  apiKey: process.env.FIREBASE_API_KEY,
  appId: process.env.FIREBASE_APP_ID_WEB,
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID,
  projectId: process.env.FIREBASE_PROJECT_ID,
  authDomain: process.env.FIREBASE_AUTH_DOMAIN,
  storageBucket: process.env.FIREBASE_STORAGE_BUCKET,
};
if (process.env.FIREBASE_MEASUREMENT_ID &&
    String(process.env.FIREBASE_MEASUREMENT_ID).trim() !== "") {
  firebaseConfig.measurementId = process.env.FIREBASE_MEASUREMENT_ID;
}

const configJson = JSON.stringify(firebaseConfig, null, 0);

const outPath = path.join(__dirname, "..", "web", "firebase-messaging-sw.js");
const contents = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-firebase-messaging-sw.js — do not edit by hand.
importScripts("https://www.gstatic.com/firebasejs/12.4.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/12.4.0/firebase-messaging-compat.js");

firebase.initializeApp(${configJson});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  // If payload already includes a Notification payload, Chrome/FCM may display
  // it automatically in the background. Showing another one here causes duplicates.
  if (payload && payload.notification) {
    return;
  }
  const title = (payload.notification && payload.notification.title) || "Parkour·Spot";
  const body = (payload.notification && payload.notification.body) || "";
  const data = Object.assign({}, payload.data || {});
  const link =
    (payload.fcmOptions && payload.fcmOptions.link) ||
    data.openUrl ||
    null;
  const openUrl = link || (self.location.origin + "/profile/notifications");
  const options = {
    body: body,
    icon: "/icons/Icon-192.png",
    badge: "/icons/Icon-192.png",
    data: Object.assign(data, {openUrl: openUrl}),
  };
  return self.registration.showNotification(title, options);
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const data = event.notification.data || {};
  let openUrl = data.openUrl;
  if (!openUrl && data.clickPath) {
    openUrl = self.location.origin + String(data.clickPath);
  }
  if (!openUrl) {
    openUrl = self.location.origin + "/profile/notifications";
  }
  event.waitUntil(
    clients.matchAll({type: "window", includeUncontrolled: true}).then((windowClients) => {
      for (let i = 0; i < windowClients.length; i++) {
        const client = windowClients[i];
        if (client.url.startsWith(self.location.origin) && "focus" in client) {
          if ("navigate" in client && typeof client.navigate === "function") {
            return client.navigate(openUrl).then((c) => (c ? c.focus() : client.focus()));
          }
          client.focus();
          return Promise.resolve();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(openUrl);
      }
    })
  );
});
`;

fs.writeFileSync(outPath, contents, "utf8");
console.log("Wrote", outPath);
